-- Migration 29: order management (2026-11-08, user brief docs/order-management-brief.md).
-- 1. Auto order number: orders.order_number — human-readable, sequential
--    per workspace (ASI-0001, ASI-0002, ...). The counter table makes the
--    increment atomic (one INSERT ... ON CONFLICT ... RETURNING per order).
-- 2. Payment method: cod | advance | fifty_fifty (default cod — the
--    customer pays on delivery unless the owner records otherwise).
-- 3. Delivery charge snapshot: orders.delivery_charge_paisa — the charge
--    resolved from the owner's configured rules at order time, so the bill
--    and the receipt never change when the rules change later.
-- 4. handled_by: 'ai' (the AI agent talked to the customer) or 'agent'
--    (a human on the team did). Shown in the order detail panel.
-- 5. invoice_token: unguessable token for the public invoice link
--    (/invoice/<token>) the customer clicks to view the invoice.
-- 6. receipt_image_url: URL of the generated receipt image, when one exists.
--    (Receipt images are NOT generated by @vercel/og — tested 2026-11-08:
--    Satori cannot shape Bengali conjuncts, they render as dotted circles.
--    The invoice LINK is the working receipt until a proper renderer lands.)
-- Statuses are free text on orders.status (no CHECK); the valid set is now:
-- pending | on_hold | approved | processing | ready | ready_to_ship |
-- in_transit | delivered | cancelled | returned | damaged | in_store.
-- The owner picks ANY of these manually in the detail panel (the old
-- forward-only transition rule is retired by the API in this same change).

ALTER TABLE orders ADD COLUMN IF NOT EXISTS order_number TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS payment_method TEXT NOT NULL DEFAULT 'cod'
  CHECK (payment_method IN ('cod', 'advance', 'fifty_fifty'));
ALTER TABLE orders ADD COLUMN IF NOT EXISTS delivery_charge_paisa BIGINT NOT NULL DEFAULT 0;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS handled_by TEXT NOT NULL DEFAULT 'ai'
  CHECK (handled_by IN ('ai', 'agent'));
ALTER TABLE orders ADD COLUMN IF NOT EXISTS invoice_token TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS receipt_image_url TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS idx_orders_workspace_number ON orders (workspace_id, order_number);
CREATE UNIQUE INDEX IF NOT EXISTS idx_orders_invoice_token ON orders (invoice_token) WHERE invoice_token IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_orders_workspace_status ON orders (workspace_id, status);
CREATE INDEX IF NOT EXISTS idx_orders_workspace_customer ON orders (workspace_id, customer_id);

CREATE TABLE IF NOT EXISTS workspace_order_counters (
  workspace_id UUID PRIMARY KEY,
  last_number INTEGER NOT NULL DEFAULT 0,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Backfill: number the orders that exist already, oldest first per
-- workspace, and seed each workspace's counter to its highest number.
UPDATE orders o SET order_number = 'ASI-' || LPAD(s.seq::text, 4, '0')
FROM (
  SELECT id, ROW_NUMBER() OVER (PARTITION BY workspace_id ORDER BY created_at ASC) AS seq
  FROM orders WHERE order_number IS NULL
) s
WHERE o.id = s.id;

INSERT INTO workspace_order_counters (workspace_id, last_number)
SELECT workspace_id, COUNT(*) FROM orders GROUP BY workspace_id
ON CONFLICT (workspace_id) DO UPDATE
  SET last_number = GREATEST(workspace_order_counters.last_number, EXCLUDED.last_number),
      updated_at = now();
